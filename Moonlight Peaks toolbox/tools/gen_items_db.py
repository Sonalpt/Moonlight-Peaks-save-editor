"""Generate overlay/source/items_db.inc from the save editor's data/items.js.

usage: python3 tools/gen_items_db.py [path to data/items.js]
       (default: ../data/items.js, the save editor's database in this repository)

Each entry: SerializedGuid parts (in-memory .NET byte order), max stack,
flags (1 = hidden: dev/test/deprecated item), category index, English name.
Sorted by GUID so the overlay can binary-search it.
"""
import json
import os
import re
import sys
import uuid

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', '..', 'data', 'items.js')
out = os.path.join(here, '..', 'overlay', 'source', 'items_db.inc')
db = json.loads(re.search(r'window.MP_ITEM_DB = (.*);\n', open(src, encoding='utf-8').read()).group(1))

cats = sorted({v['c'] for v in db.values()})
rows = []
for g, v in db.items():
    b = uuid.UUID(g).bytes_le
    p1, p2 = int.from_bytes(b[:8], 'little'), int.from_bytes(b[8:], 'little')
    name = v['n'].replace('\\', '\\\\').replace('"', '\\"')
    rows.append((p1, p2, min(v['s'], 2147483647), 1 if v.get('h') else 0, cats.index(v['c']), name))
rows.sort()

with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/gen_items_db.py from the save editor item database. Do not edit.\n')
    f.write('static const char* const kItemCategories[] = {%s};\n' % ', '.join('"%s"' % c for c in cats))
    f.write('static const ItemInfo kItems[] = {\n')
    for p1, p2, s, h, c, n in rows:
        f.write('    {0x%016XULL, 0x%016XULL, %d, %d, %d, "%s"},\n' % (p1, p2, s, h, c, n))
    f.write('};\n')
print('wrote %d items, %d categories -> %s' % (len(rows), len(cats), os.path.normpath(out)))
